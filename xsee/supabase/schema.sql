create table if not exists public.teachers (
  id integer generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id integer generated by default as identity primary key,
  student_id text not null unique,
  full_name text not null,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.exams (
  id integer generated by default as identity primary key,
  exam_name text not null,
  form_url text not null,
  form_id text not null unique,
  status text not null default 'active' check (status in ('active', 'closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.sessions (
  id integer generated by default as identity primary key,
  exam_id integer not null references public.exams(id) on delete cascade,
  student_id integer not null references public.students(id) on delete cascade,
  started_at timestamptz not null,
  ended_at timestamptz,
  last_seen timestamptz not null,
  status text not null,
  prev_status text,
  tab_switch_count integer not null default 0,
  idle_count integer not null default 0,
  warning_count integer not null default 0,
  total_away_seconds integer not null default 0,
  unique (exam_id, student_id)
);

create table if not exists public.logs (
  id integer generated by default as identity primary key,
  event_id text not null unique,
  exam_id integer references public.exams(id) on delete cascade,
  student_id integer not null references public.students(id) on delete cascade,
  event_type text not null,
  detail text,
  away_seconds integer,
  client_time text,
  server_time timestamptz not null default now()
);

create index if not exists idx_logs_exam_student on public.logs (exam_id, student_id, id);
create index if not exists idx_logs_student_time on public.logs (student_id, server_time);
create index if not exists idx_sessions_exam on public.sessions (exam_id);

create or replace function public.process_xsee_event(
  p_event_id text,
  p_exam_id integer,
  p_student_id integer,
  p_event_type text,
  p_detail text,
  p_away_seconds integer,
  p_client_time text,
  p_server_time timestamptz,
  p_closed boolean
) returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  inserted_count integer;
  current_session public.sessions%rowtype;
  next_status text;
  next_ended_at timestamptz;
begin
  insert into public.logs (event_id, exam_id, student_id, event_type, detail, away_seconds, client_time, server_time)
  values (p_event_id, p_exam_id, p_student_id, p_event_type, p_detail, p_away_seconds, p_client_time, p_server_time)
  on conflict (event_id) do nothing;
  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then
    return false;
  end if;

  if p_exam_id is null then
    return true;
  end if;

  insert into public.sessions (exam_id, student_id, started_at, last_seen, status)
  values (p_exam_id, p_student_id, p_server_time, p_server_time,
          case when p_event_type = 'TRACKING_OFF' then 'UNTRACKED' else 'ACTIVE' end)
  on conflict (exam_id, student_id) do nothing;

  select * into current_session
  from public.sessions
  where exam_id = p_exam_id and student_id = p_student_id
  for update;

  next_status := current_session.status;
  next_ended_at := current_session.ended_at;
  if p_event_type = 'SESSION_START' and current_session.status <> 'SUBMITTED' then
    next_status := 'ACTIVE';
    next_ended_at := null;
  elsif p_event_type = 'SESSION_END' then
    next_ended_at := p_server_time;
    if p_closed then
      if current_session.status <> 'SUBMITTED' then next_status := 'CLOSED'; end if;
    else
      next_status := 'SUBMITTED';
    end if;
  elsif p_event_type in ('TAB_SWITCH', 'WINDOW_BLUR') then
    next_status := 'AWAY';
  elsif p_event_type = 'RETURNED' and current_session.status = 'AWAY' then
    next_status := 'ACTIVE';
  elsif p_event_type = 'IDLE_WARNING' then
    next_status := 'IDLE';
  elsif p_event_type = 'WARNING_ACKNOWLEDGED' and current_session.status = 'IDLE' then
    next_status := 'ACTIVE';
  end if;

  update public.sessions
  set status = next_status,
      ended_at = next_ended_at,
      last_seen = p_server_time,
      tab_switch_count = tab_switch_count + case when p_event_type in ('TAB_SWITCH', 'WINDOW_BLUR') then 1 else 0 end,
      idle_count = idle_count + case when p_event_type = 'IDLE_WARNING' then 1 else 0 end,
      warning_count = warning_count + case when p_event_type in ('TAB_SWITCH', 'WINDOW_BLUR', 'IDLE_WARNING') then 1 else 0 end,
      total_away_seconds = total_away_seconds + case when p_event_type = 'RETURNED' then coalesce(p_away_seconds, 0) else 0 end
  where id = current_session.id;

  return true;
end;
$$;

